/* ─────────────────────────────────────────────────────────────
   GLSL LAB — universal shader builder
   Pixel on Kaspa · art lab

   One fragment shader, assembled from swappable modules:

     coords → [DOMAIN] → [WARP] → [FIELD / SDF] → [SHADE] → [PALETTE] → [POST]

   Structural choices (which module, how many iterations) are
   #define-injected and the program is recompiled + cached.
   Everything continuous stays a uniform, so sliders are smooth.

   Two regimes:
     2D  — a scalar field on the plane (graphic, cheap, pixel-art friendly)
     3D  — a raymarched distance field, rendered as surface or as volume

   Nothing here knows about the DOM. GLSLLabShader.build(cfg) → source.
   ───────────────────────────────────────────────────────────── */
